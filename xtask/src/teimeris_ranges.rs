//! `docs/05-testing/teimeris-ranges-measured.md`: what each of the
//! Teimeris engine's data blocks weighs and the digest it must have,
//! rendered from the manifest the adapter compiles in
//! (`adapters/ephemeris-teimeris/rust/data/ranges.json`, which
//! `teistro-ephemeris-teimeris-ranges` writes from the engine's full set),
//! and the gate on it.
//!
//! The manifest is what the adapter checks a downloaded range against,
//! so this page and that check read one file: a size printed here is the
//! size a download is refused for missing.

use std::fmt::Write as _;
use std::path::Path;

use serde::Deserialize;
use teistro_port_ephemeris::sefile;

use crate::generated::{Output, check, write};
use crate::measure::count;

const PAGE: &str = "docs/05-testing/teimeris-ranges-measured.md";
const MANIFEST: &str = "adapters/ephemeris-teimeris/rust/data/ranges.json";
const SCHEMA: &str = "teistro.teimeris-ranges/1";

/// The block every package carries built in: 1800 to 2399.
const BUILT_IN: i32 = 18;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Manifest {
    schema: String,
    files: Vec<Entry>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Entry {
    file: String,
    bytes: u64,
    sha256: String,
    jd_start: f64,
    jd_end: f64,
}

/// One block's three files, as the manifest has them.
struct Block<'a> {
    century: i32,
    planets: &'a Entry,
    moon: &'a Entry,
    asteroids: Option<&'a Entry>,
}

impl Block<'_> {
    fn needed(&self) -> u64 {
        self.planets.bytes + self.moon.bytes
    }

    fn whole(&self) -> u64 {
        self.needed() + self.asteroids.map_or(0, |file| file.bytes)
    }
}

fn read(root: &Path) -> Result<Manifest, String> {
    let text =
        std::fs::read_to_string(root.join(MANIFEST)).map_err(|e| format!("{MANIFEST}: {e}"))?;
    let manifest: Manifest = serde_json::from_str(&text).map_err(|e| format!("{MANIFEST}: {e}"))?;
    if manifest.schema != SCHEMA {
        return Err(format!(
            "{MANIFEST} is schema `{}`; this page reads `{SCHEMA}`",
            manifest.schema
        ));
    }
    Ok(manifest)
}

/// The blocks, earliest first, each with both needed files; a planet
/// block without its Moon, or a file that names no block, is an error.
fn blocks(manifest: &Manifest) -> Result<Vec<Block<'_>>, String> {
    let find = |stem: &str, century: i32| {
        let name = sefile::block_name(stem, century);
        manifest.files.iter().find(|file| file.file == name)
    };
    let mut centuries = Vec::new();
    for file in &manifest.files {
        let Some((first, _)) = sefile::block_years(&file.file) else {
            return Err(format!("{MANIFEST}: `{}` names no block", file.file));
        };
        if !centuries.contains(&(first / 100)) {
            centuries.push(first / 100);
        }
    }
    centuries.sort_unstable();
    centuries
        .into_iter()
        .map(|century| {
            let (Some(planets), Some(moon)) = (find("sepl", century), find("semo", century)) else {
                return Err(format!(
                    "{MANIFEST}: the block from year {} lacks its planet or Moon file",
                    century * 100
                ));
            };
            Ok(Block {
                century,
                planets,
                moon,
                asteroids: find("seas", century),
            })
        })
        .collect()
}

/// A year as a reader writes it, with no year 0.
fn year(astronomical: i32) -> String {
    if astronomical <= 0 {
        format!("{} BC", 1 - astronomical)
    } else {
        astronomical.to_string()
    }
}

/// A Julian day's year, near enough to name it: the mean year from J2000.
#[allow(
    clippy::cast_possible_truncation,
    reason = "a year of the published span fits an i32 many times over"
)]
fn year_of(jd: f64) -> i32 {
    (2000.0 + (jd - 2_451_545.0) / 365.25).floor() as i32
}

/// Bytes as megabytes, two places.
#[allow(
    clippy::cast_precision_loss,
    reason = "a size under a gigabyte is exact in an f64"
)]
fn megabytes(bytes: u64) -> String {
    format!("{:.2}", bytes as f64 / 1_000_000.0)
}

#[allow(
    clippy::cast_possible_truncation,
    reason = "a size under a gigabyte fits a usize"
)]
fn bytes(value: u64) -> String {
    count(value as usize)
}

fn page(manifest: &Manifest, blocks: &[Block<'_>]) -> String {
    let mut out = String::new();
    let built_in = blocks.iter().find(|block| block.century == BUILT_IN);
    let first = blocks.first();
    let last = blocks.last();
    let needed: u64 = blocks.iter().map(Block::needed).sum();
    let whole: u64 = blocks.iter().map(Block::whole).sum();
    let _ = writeln!(out, "# Teimeris data ranges\n");
    let _ = writeln!(
        out,
        "Status: generated by `cargo xtask teimeris-ranges` from `{MANIFEST}`, which \
         `teistro-ephemeris-teimeris-ranges` writes from the engine's full data set; held by \
         `cargo xtask check-teimeris-ranges`. Do not edit by hand.\n"
    );
    if let Some(block) = built_in {
        let _ = writeln!(
            out,
            "Every package of the Teimeris adapter carries **{}–{}** in its own binary, the \
             engine's `MODERN` tier: `{}`, `{}` and `{}`, {} bytes. That is what a provider \
             reads when nothing else is named, on every platform, a phone and the web \
             included. Any other years are a **range** an app adds: it downloads a block's \
             files into its own storage and names them (Rust \
             `TeimerisProvider::data().file(path)` or `.bytes(name, bytes)`; `files` in every \
             binding's `teimeris(…)`). Each file is checked against the size and SHA-256 \
             below before it is read, and one that differs is refused by name, which is what \
             a download cut short looks like. A set with a hole in it (a block missing \
             between two others, or a planet block without its Moon) is refused with the \
             files that fill it.\n",
            year(block.century * 100),
            year(block.century * 100 + 599),
            block.planets.file,
            block.moon.file,
            block.asteroids.map_or("", |file| file.file.as_str()),
            bytes(block.whole()),
        );
    }
    let _ = writeln!(
        out,
        "A block is two files an app needs, the planets' (`sepl`) and the Moon's (`semo`), \
         and a third, the asteroids' (`seas`), read only for a chart that names Chiron, \
         Ceres, Pallas, Juno or Vesta. The files are the Swiss Ephemeris's own, which the \
         engine reads unchanged; on 2026-10-20 every name and size here was found in that \
         distribution's `ephe` directory (github.com/aloistr/swisseph), and three files' \
         digests were checked byte for byte.\n"
    );
    let _ = writeln!(
        out,
        "{} blocks, {} files. Their needed files weigh {} bytes in all ({} MB), and \
         with the asteroids' {} bytes ({} MB).\n",
        blocks.len(),
        manifest.files.len(),
        bytes(needed),
        megabytes(needed),
        bytes(whole),
        megabytes(whole),
    );
    if let (Some(first), Some(last)) = (first, last) {
        let _ = writeln!(
            out,
            "The years are those the blocks' names give. The earliest and the latest hold \
             less: the \
             first block's files begin at JD {:.1} (about {}) and the last's end at JD {:.1} \
             (about {}), and a provider holding either claims only that.\n",
            first.planets.jd_start.max(first.moon.jd_start),
            year(year_of(first.planets.jd_start.max(first.moon.jd_start))),
            last.planets.jd_end.min(last.moon.jd_end),
            year(year_of(last.planets.jd_end.min(last.moon.jd_end))),
        );
    }
    out.push_str(&tables(manifest, blocks));
    out
}

/// The two tables: each block, then each file with its digest.
fn tables(manifest: &Manifest, blocks: &[Block<'_>]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "## 1. The blocks\n");
    let _ = writeln!(
        out,
        "| Years | Planets | Moon | Asteroids | Needed, bytes | Needed, MB |"
    );
    let _ = writeln!(out, "|---|---|---|---|---:|---:|");
    for block in blocks {
        let marked = if block.century == BUILT_IN {
            " (built in)"
        } else {
            ""
        };
        let _ = writeln!(
            out,
            "| {}–{}{marked} | `{}` | `{}` | {} | {} | {} |",
            year(block.century * 100),
            year(block.century * 100 + 599),
            block.planets.file,
            block.moon.file,
            block
                .asteroids
                .map_or_else(|| String::from("none"), |file| format!("`{}`", file.file)),
            bytes(block.needed()),
            megabytes(block.needed()),
        );
    }
    let _ = writeln!(out, "\n## 2. The files\n");
    let _ = writeln!(
        out,
        "The size and digest each file is checked against, in the manifest's order.\n"
    );
    let _ = writeln!(out, "| Entry | Bytes | SHA-256 |");
    let _ = writeln!(out, "|---|---:|---|");
    for file in &manifest.files {
        let _ = writeln!(
            out,
            "| `{}` | {} | `{}` |",
            file.file,
            bytes(file.bytes),
            file.sha256
        );
    }
    out
}

fn outputs(root: &Path) -> Result<Vec<Output>, i32> {
    let rendered = read(root).and_then(|manifest| {
        let blocks = blocks(&manifest)?;
        Ok(page(&manifest, &blocks))
    });
    match rendered {
        Ok(text) => Ok(vec![Output::new(PAGE, text)]),
        Err(message) => {
            eprintln!("{message}");
            Err(1)
        }
    }
}

/// Writes the page.
pub(crate) fn generate(root: &Path) -> i32 {
    match outputs(root) {
        Ok(outputs) => write(root, &outputs),
        Err(code) => code,
    }
}

/// Regenerates the page in memory and fails on any difference.
pub(crate) fn check_generated(root: &Path) -> i32 {
    match outputs(root) {
        Ok(outputs) => check(root, &outputs, "cargo xtask teimeris-ranges"),
        Err(code) => code,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file(name: &str, bytes: u64) -> Entry {
        Entry {
            file: name.to_owned(),
            bytes,
            sha256: String::from("00"),
            jd_start: 0.0,
            jd_end: 1.0,
        }
    }

    #[test]
    fn a_planet_block_without_its_moon_is_refused() {
        let manifest = Manifest {
            schema: SCHEMA.to_owned(),
            files: vec![
                file("sepl_18.se1", 1),
                file("semo_18.se1", 2),
                file("sepl_24.se1", 3),
            ],
        };
        let refusal = blocks(&manifest).err().unwrap_or_default();
        assert!(refusal.contains("2400"), "{refusal}");
    }

    #[test]
    fn a_year_has_no_zero() {
        assert_eq!(year(0), "1 BC");
        assert_eq!(year(-600), "601 BC");
        assert_eq!(year(1800), "1800");
        assert_eq!(year_of(2_451_545.0), 2000);
    }
}

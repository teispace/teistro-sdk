/// One cell of the chakra.
///
/// ```
/// use teistro_core::catalogue::TithiClass;
/// use teistro_gochar::sarvatobhadra::{Cell, chakra};
///
/// let grid = chakra();
/// assert_eq!(grid[4][4], Cell::Tithi { class: TithiClass::Purna });

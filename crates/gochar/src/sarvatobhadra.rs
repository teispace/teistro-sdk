/// let mut sky = [Transit::new(Rashi::Taurus, 15.0); 9];
/// sky[Graha::Ketu as usize] = Transit::new(Rashi::Scorpio, 15.0);
/// let motions = [Motion::Fast, Motion::Fast, Motion::Fast, Motion::Fast, Motion::Mean];
/// let native = NativePoints {
///     nakshatra: Nakshatra::Swati,
///     rashi: Rashi::Libra,
///     tithi: Tithi::ShuklaPratipada,
///     vara: Vara::Ravivara,
///     name: None,
/// };
/// let reading = sarvatobhadra(&sky, &motions, &native, SarvatobhadraRules::TEXT)?;
/// assert_eq!(reading.rules, SarvatobhadraRules::TEXT);
/// assert!(reading.malefic_points <= 5);
/// # Ok::<(), teistro_core::error::Error>(())
/// ```
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase")]
pub struct SarvatobhadraReading {
    /// The readings it was taken under.
    pub rules: SarvatobhadraRules,
    /// The native's points.
    pub native: NativePoints,
    /// Each graha's, the Sun to Ketu.
    pub grahas: [GrahaVedha; 9],
    /// Each of the native's points, in v. 28's order and the weekday last;
    /// the letter and vowel only with a name.
    pub points: Vec<PointVedha>,
    /// How many of v. 28's five (star, letter, vowel, tithi, sign) a
    /// malefic strikes: all five is the verse's "does not live".
    pub malefic_points: u8,
}

/// Each graha's nature, whether the Moon wanes, and the malefics that join
/// a benefic in its sign.
fn natures(transits: &[Transit; 9]) -> [(Nature, bool, Vec<Graha>); 9] {
    let longitude = |graha: Graha| {
        transits
            .get(graha as usize)
            .map_or(0.0, |t| t.sign.start_deg() + t.degrees)
    };
    let waning = (longitude(Graha::Moon) - longitude(Graha::Sun)).rem_euclid(360.0) >= 180.0;
    let malefic = |graha: Graha| match graha {
        Graha::Sun | Graha::Mars | Graha::Saturn | Graha::Rahu | Graha::Ketu => true,
        Graha::Moon => waning,
        _ => false,
    };
    let sign = |graha: Graha| transits.get(graha as usize).map(|t| t.sign);
    GRAHAS.map(|graha| {
        let moon_waning = graha == Graha::Moon && waning;
        if malefic(graha) {
            return (Nature::Malefic, moon_waning, Vec::new());
        }
        let joined_by: Vec<Graha> = GRAHAS
            .into_iter()
            .filter(|other| *other != graha && malefic(*other) && sign(*other) == sign(graha))
            .collect();
        let nature = if joined_by.is_empty() {
            Nature::Benefic
        } else {
            Nature::Malefic
        };
        (nature, moon_waning, joined_by)
    })
}

/// The lines `graha` looks along.
fn lines_of(graha: Graha, motion: Motion, sight: Sight) -> Vec<Line> {
    let five = matches!(
        graha,
        Graha::Mars | Graha::Mercury | Graha::Jupiter | Graha::Venus | Graha::Saturn
    );
    let one_line = match sight {
        Sight::AllThree => false,
        Sight::Text => five,
        Sight::OneEach => true,
    };
    if one_line {
        vec![motion.line()]
    } else {
        Line::ALL.to_vec()
    }
}

/// The native's points a reach strikes.
fn points_struck(
    reach: Reach,
    native: &NativePoints,
    letter: Option<&LetterReach>,
    stands_in: Star,
) -> Vec<VedhaPoint> {
    let mut points = Vec::new();
    let Some(cell) = reach.cell() else {
        // v. 24: the graha stands in the star of the letter's pada.
        if letter.is_some_and(|l| l.stars.iter().any(|s| Star::of(*s) == stands_in)) {
            points.push(VedhaPoint::Letter);
        }
        return points;
    };
    match cell {
        Cell::Star { star } if star == Star::of(native.nakshatra) => {
            points.push(VedhaPoint::Nakshatra);
        }
        Cell::Letter { letter: struck } if letter.is_some_and(|l| l.cells.contains(&struck)) => {
            points.push(VedhaPoint::Letter);
        }
        Cell::Vowel { vowel } => {
            if native
                .name
                .is_some_and(|name| name.vowel == vowel || name.vowel.pair() == vowel)
            {
                points.push(VedhaPoint::Vowel);
            }
        }
        Cell::Rashi { rashi } if rashi == native.rashi => points.push(VedhaPoint::Rashi),
        Cell::Tithi { class } => {
            if class == native.tithi.attributes().class {
                points.push(VedhaPoint::Tithi);
            }
            if varas(class).contains(&native.vara) {
                points.push(VedhaPoint::Vara);
            }
        }
        _ => {}
    }
    points
}

/// The chakra's vedha over a sky: for each graha, where it stands, the
/// lines it looks along, its nature, every cell it strikes and the
/// native's points among them; and for each point, the malefics and the
/// benefics that strike it. It reports the verses' clauses and scores
/// nothing; [`crate::gochar`]'s verdicts are its own and untouched.
///
/// `transits` are the nine's sidereal places, the Sun to Ketu; `motions`
/// the five's from Mars, in the catalogue's order (Mars, Mercury,
/// Jupiter, Venus, Saturn), which [`Motion::by_the_sun`] gives by the
/// text where an ephemeris's is not wanted.
///
/// # Errors
///
/// `native.name.letter` that is not a Devanagari letter the chakra reads
/// (vv. 5, 22–24), naming the field.
///
/// ```
/// use teistro_core::catalogue::{Nakshatra, Rashi, Tithi, Vara};
/// use teistro_gochar::Transit;
/// use teistro_gochar::sarvatobhadra::{
///     Motion, NameSounds, NativePoints, SarvatobhadraRules, Vowel, sarvatobhadra,
/// };
///
/// let sky = [Transit::new(Rashi::Aries, 0.0); 9];
/// let native = NativePoints {
///     nakshatra: Nakshatra::Swati,
///     rashi: Rashi::Libra,
///     tithi: Tithi::ShuklaPratipada,
///     vara: Vara::Ravivara,
///     name: Some(NameSounds { letter: 'k', vowel: Vowel::A }),
/// };
/// let refused = sarvatobhadra(&sky, &[Motion::Fast; 5], &native, SarvatobhadraRules::TEXT)
///     .unwrap_err();
/// assert_eq!(refused.field(), Some("native.name.letter"));
/// ```
pub fn sarvatobhadra(
    transits: &[Transit; 9],
    motions: &[Motion; 5],
    native: &NativePoints,
    rules: SarvatobhadraRules,
) -> Result<SarvatobhadraReading, Error> {
    let letter = match native.name {
        None => None,
        Some(name) => Some(letter_reach(name.letter).ok_or_else(|| {
            Error::invalid_arg(format!(
                "the chakra reads no letter {:?}: a name's first letter is a Devanagari consonant or vowel",
                name.letter
            ))
            .with_field("native.name.letter")
            .with_hint(
                "pass a conjunct's first consonant, or a name that begins with a vowel by that vowel, in Devanagari",
            )
        })?),
    };
    let grid = chakra();
    let natures = natures(transits);
    let grahas = GRAHAS.map(|graha| {
        let index = graha as usize;
        let place = transits.get(index).map_or(StarPlace::at(0.0), |t| {
            StarPlace::at(t.sign.start_deg() + t.degrees)
        });
        let motion = match graha {
            Graha::Sun | Graha::Moon => Motion::Fast,
            Graha::Rahu | Graha::Ketu => Motion::Retrograde,
            _ => motions
                .get(index.saturating_sub(2))
                .copied()
                .unwrap_or(Motion::Mean),
        };
        let lines = lines_of(graha, motion, rules.sight);
        let cells = struck_cells(&grid, place, &lines, rules);
        let points = native_struck(&cells, native, letter.as_ref(), place.star);
        let (nature, waning, joined_by) =
            natures
                .get(index)
                .cloned()
                .unwrap_or((Nature::Benefic, false, Vec::new()));
        GrahaVedha {
            graha,
            place,
            motion,
            lines,
            nature,
            waning,
            joined_by,
            cells,
            points,
        }
    });
    let points = by_point(&grahas, native);
    let malefic_points = u8::try_from(
        points
            .iter()
            .filter(|p| p.point != VedhaPoint::Vara && !p.malefics.is_empty())
            .count(),
    )
    .unwrap_or(u8::MAX);
    Ok(SarvatobhadraReading {
        rules,
        native: *native,
        grahas,
        points,
        malefic_points,
    })
}

/// Every cell a graha at `place` strikes along `lines`, and from a
/// corner's juncture.
fn struck_cells(
    grid: &[[Cell; SIDE]; SIDE],
    place: StarPlace,
    lines: &[Line],
    rules: SarvatobhadraRules,
) -> Vec<Reach> {
    let mut cells: Vec<Reach> = Vec::new();
    for &line in lines {
        let passed = sight_in(grid, place.star, line);
        let struck = match (line, rules.front) {
            (Line::Front, FrontVedha::StarOnly) => passed.last().copied().into_iter().collect(),
            _ => passed,
        };
        cells.extend(struck.into_iter().map(|cell| Reach::Line { line, cell }));
    }
    if let Some(corner) = juncture(place) {
        let rings = match rules.corner {
            CornerVedha::FourVowels => 0..4,
            CornerVedha::OuterVowel => 0..1,
        };
        for ring in rings {
            if let Some(&vowel) = Vowel::ALL.get(4 * ring + corner) {
                cells.push(Reach::Corner {
                    cell: Cell::Vowel { vowel },
                });
            }
        }
        cells.push(Reach::Corner {
            cell: Cell::Tithi {
                class: TithiClass::Purna,
            },
        });
    }
    cells
}

/// The native's points among a graha's `cells`, and the letter it strikes
/// by standing in `stands_in` (v. 24), each point once with every reach.
fn native_struck(
    cells: &[Reach],
    native: &NativePoints,
    letter: Option<&LetterReach>,
    stands_in: Star,
) -> Vec<PointStrike> {
    let mut points: Vec<PointStrike> = Vec::new();
    for reach in cells.iter().copied().chain([Reach::Stands]) {
        for point in points_struck(reach, native, letter, stands_in) {
            match points.iter_mut().find(|p| p.point == point) {
                Some(strike) => strike.by.push(reach),
                None => points.push(PointStrike {
                    point,
                    by: vec![reach],
                }),
            }
        }
    }
    points
}

/// Each of the native's points with the malefics and benefics that strike
/// it: v. 28's order, the weekday last, the letter and vowel only with a
/// name.
fn by_point(grahas: &[GrahaVedha; 9], native: &NativePoints) -> Vec<PointVedha> {
    let mut kinds = vec![VedhaPoint::Nakshatra];
    if native.name.is_some() {
        kinds.extend([VedhaPoint::Letter, VedhaPoint::Vowel]);
    }
    kinds.extend([VedhaPoint::Tithi, VedhaPoint::Rashi, VedhaPoint::Vara]);
    kinds
        .into_iter()
        .map(|point| {
            let striking = |nature: Nature| {
                grahas
                    .iter()
                    .filter(|g| g.nature == nature && g.points.iter().any(|p| p.point == point))
                    .map(|g| g.graha)
                    .collect()
            };
            PointVedha {
                point,
                malefics: striking(Nature::Malefic),
                benefics: striking(Nature::Benefic),
            }
        })
        .collect()
}


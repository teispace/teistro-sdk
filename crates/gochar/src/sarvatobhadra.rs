/// A graha's motion as v. 15 sorts it (C430).
///
/// ```
/// use teistro_gochar::sarvatobhadra::{Line, Motion};
///
/// assert_eq!(Motion::Fast.line(), Line::Left);
/// assert_eq!(Motion::by_the_sun(3), Some(Motion::Mean));
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[cfg_attr(feature = "schema", schemars(rename = "VedhaMotion"))]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Motion {
    /// Fast (शीघ्र): it looks to its left.
    Fast,
    /// Mean (मध्य): it looks ahead.
    Mean,
    /// Retrograde (वक्र): it looks to its right.
    Retrograde,
}

impl Motion {
    /// The line v. 15 gives the motion.
    ///
    /// ```
    /// use teistro_gochar::sarvatobhadra::{Line, Motion};
    ///
    /// assert_eq!(Motion::Retrograde.line(), Line::Right);
    /// ```
    #[must_use]
    pub const fn line(self) -> Line {
        match self {
            Motion::Fast => Line::Left,
            Motion::Mean => Line::Front,
            Motion::Retrograde => Line::Right,
        }
    }

    /// The motion vv. 16–18 read off the Sun's sign counted from the
    /// graha's, 1 to 12, "without computing the grahas": the Sun in the
    /// 2nd, 11th or 12th, fast; the 3rd (even) or the 4th (slow), mean; the
    /// 5th to the 10th (retrograde, very and crooked), retrograde. With
    /// the Sun, in the 1st, the graha is unseen (v. 18) and has no motion
    /// here, so `None`; a house outside 1 to 12, `None` too.
    ///
    /// ```
    /// use teistro_gochar::sarvatobhadra::Motion;
    ///
    /// assert_eq!(Motion::by_the_sun(2), Some(Motion::Fast));
    /// assert_eq!(Motion::by_the_sun(7), Some(Motion::Retrograde));
    /// assert_eq!(Motion::by_the_sun(1), None);
    /// ```
    #[must_use]
    pub const fn by_the_sun(sun_from_graha: u8) -> Option<Motion> {
        match sun_from_graha {
            2 | 11 | 12 => Some(Motion::Fast),
            3 | 4 => Some(Motion::Mean),
            5..=10 => Some(Motion::Retrograde),
            _ => None,
        }
    }

    /// The motion v. 15 sorts a computed speed into, against the graha's
    /// mean daily motion: backwards, retrograde; faster than the mean,
    /// fast; otherwise mean, which takes in the slow (मन्द), "less than
    /// the even and the mean" as the tika on vv. 16–18 has it. The tika
    /// gives vv. 16–18's rule as the motion "without computing the
    /// grahas" (ग्रहगणितं विना), so a computed speed is what the rule
    /// stands in for (C430).
    ///
    /// ```
    /// use teistro_gochar::sarvatobhadra::Motion;
    ///
    /// // Mars's mean motion is about 0.524° a day.
    /// assert_eq!(Motion::by_speed(0.7, 0.524), Motion::Fast);
    /// assert_eq!(Motion::by_speed(0.3, 0.524), Motion::Mean);
    /// assert_eq!(Motion::by_speed(-0.2, 0.524), Motion::Retrograde);
    /// ```
    #[must_use]
    pub fn by_speed(speed_deg_per_day: f64, mean_deg_per_day: f64) -> Motion {
        if speed_deg_per_day < 0.0 {
            Motion::Retrograde
        } else if speed_deg_per_day > mean_deg_per_day {
            Motion::Fast
        } else {
            Motion::Mean
        }
    }
}

/// Where a graha stands among the stars: the chakra's star, and the star
/// and pada of the 27 that v. 26's junctures are counted in.
///
/// ```
/// use teistro_core::catalogue::Nakshatra;
/// use teistro_gochar::sarvatobhadra::{Star, StarPlace};
///
/// let place = StarPlace::at(45.0);
/// assert_eq!((place.star, place.nakshatra, place.pada), (Star::of(Nakshatra::Rohini), Nakshatra::Rohini, 2));
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase")]
pub struct StarPlace {
    /// The chakra's star: Abhijit over its span, else the nakshatra.
    pub star: Star,
    /// The nakshatra of the 27.
    pub nakshatra: Nakshatra,
    /// Its pada, 1 to 4.
    pub pada: u8,
}

/// Abhijit's span in arcminutes of sidereal longitude: 276°40′ to
/// 280°53′20″ (C428).
const ABHIJIT_MIN: (f64, f64) = (16_600.0, 16_600.0 + 760.0 / 3.0);

impl StarPlace {
    /// The place of a sidereal longitude, in degrees.
    ///
    /// ```
    /// use teistro_core::catalogue::Nakshatra;
    /// use teistro_gochar::sarvatobhadra::{Star, StarPlace};
    ///
    /// let place = StarPlace::at(277.0);
    /// assert_eq!(place.star, Star::Abhijit);
    /// assert_eq!((place.nakshatra, place.pada), (Nakshatra::UttaraAshadha, 4));
    /// assert_eq!(StarPlace::at(281.0).star, Star::of(Nakshatra::Shravana));
    /// ```
    #[must_use]
    pub fn at(longitude_deg: f64) -> StarPlace {
        let minutes = longitude_deg.rem_euclid(360.0) * 60.0;
        #[allow(
            clippy::cast_possible_truncation,
            clippy::cast_sign_loss,
            reason = "arcminutes in [0, 21600) over 800 are a star 0 to 26, and the rest over 200 a pada 0 to 3"
        )]
        let (index, quarter) = {
            let index = ((minutes / 800.0) as usize).min(26);
            let within = minutes - 800.0 * f64::from(u8::try_from(index).unwrap_or(0));
            (index, ((within / 200.0) as u8).min(3))
        };
        let nakshatra = Nakshatra::ALL
            .get(index)
            .copied()
            .unwrap_or(Nakshatra::Ashwini);
        let star = if (ABHIJIT_MIN.0..ABHIJIT_MIN.1).contains(&minutes) {
            Star::Abhijit
        } else {
            Star::of(nakshatra)
        };
        StarPlace {
            star,
            nakshatra,
            pada: quarter + 1,
        }
    }
}

/// The corner whose juncture a place stands at (v. 26): the last pada of
/// the star before the corner or the first of the star after it, `0` the
/// north-east to `3` the north-west.
fn juncture(place: StarPlace) -> Option<usize> {
    const JUNCTURES: [(Nakshatra, Nakshatra); 4] = [
        (Nakshatra::Bharani, Nakshatra::Krittika),
        (Nakshatra::Ashlesha, Nakshatra::Magha),
        (Nakshatra::Vishakha, Nakshatra::Anuradha),
        (Nakshatra::Shravana, Nakshatra::Dhanishtha),
    ];
    JUNCTURES.iter().position(|(before, after)| {
        (place.nakshatra == *before && place.pada == 4)
            || (place.nakshatra == *after && place.pada == 1)
    })
}


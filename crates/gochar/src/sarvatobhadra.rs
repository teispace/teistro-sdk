/// # Ok::<(), serde_json::Error>(())
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[cfg_attr(feature = "schema", schemars(rename = "ChakraCell"))]
#[serde(tag = "cell", rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Cell {
    /// A star of the outer ring.
    Star {
        /// Which.
        star: Star,
    },
    /// A vowel at a corner.
    Vowel {
        /// Which.
        vowel: Vowel,
    },
    /// One of v. 5's twenty letters, in Devanagari; the first is a.
    Letter {
        /// Which.
        letter: char,
    },
    /// A sign.
    Rashi {
        /// Which.
        rashi: Rashi,
    },
    /// A tithi group, with the weekdays [`varas`] gives it.
    Tithi {
        /// Which.
        class: TithiClass,
    },
}

/// The weekdays a tithi group's cell holds (v. 8): Tuesday and Sunday in
/// Nanda, Wednesday and Monday in Bhadra, Thursday in Jaya, Friday in
/// Rikta, Saturday in Purna.
///
/// ```
/// use teistro_core::catalogue::{TithiClass, Vara};
/// use teistro_gochar::sarvatobhadra::varas;
///
/// assert_eq!(varas(TithiClass::Purna), &[Vara::Shanivara]);
/// ```
#[must_use]
pub fn varas(class: TithiClass) -> &'static [Vara] {
    match class {
        TithiClass::Nanda => &[Vara::Mangalavara, Vara::Ravivara],
        TithiClass::Bhadra => &[Vara::Budhavara, Vara::Somavara],
        TithiClass::Jaya => &[Vara::Guruvara],
        TithiClass::Rikta => &[Vara::Shukravara],
        TithiClass::Purna => &[Vara::Shanivara],
        // A group the catalogue adds later holds none until a text says.
        _ => &[],
    }
}

/// The chakra's width.
const SIDE: usize = 9;

/// A cell's place: its row counted from the east, the top as the print
/// draws it, and its column from the north, the left.
type At = (usize, usize);

/// The four corners of ring `ring` (0 the outermost), in v. 3's order:
/// north-east, south-east, south-west, north-west.
const fn corners(ring: usize) -> [At; 4] {
    let (lo, hi) = (ring, SIDE - 1 - ring);
    [(lo, lo), (lo, hi), (hi, hi), (hi, lo)]
}

/// The cells of ring `ring` between its corners, clockwise from the
/// north-east as vv. 4–7 fill them: the east side, the south, the west
/// and the north.
fn ring_sides(ring: usize) -> Vec<At> {
    let (lo, hi) = (ring, SIDE - 1 - ring);
    let east = (lo + 1..hi).map(move |column| (lo, column));
    let south = (lo + 1..hi).map(move |row| (row, hi));
    let west = (lo + 1..hi).rev().map(move |column| (hi, column));
    let north = (lo + 1..hi).rev().map(move |row| (row, lo));
    east.chain(south).chain(west).chain(north).collect()
}

/// The `n`th member of ring `ring`'s sides: the stars, the letters, the
/// signs from Taurus, then the four tithi groups.
fn member(ring: usize, n: usize) -> Option<Cell> {
    match ring {
        0 => STARS.get(n).map(|&star| Cell::Star { star }),
        1 => LETTERS.get(n).map(|&letter| Cell::Letter { letter }),
        2 => Rashi::ALL
            .get((n + 1) % 12)
            .map(|&rashi| Cell::Rashi { rashi }),
        _ => TITHI_SIDES.get(n).map(|&class| Cell::Tithi { class }),
    }
}

/// The chakra, generated by vv. 2–9's rule: row 0 is the east and column 0
/// the north, as the 1946 print draws it.
///
/// ```
/// use teistro_core::catalogue::{Nakshatra, TithiClass};
/// use teistro_gochar::sarvatobhadra::{Cell, Star, Vowel, chakra};
///
/// let grid = chakra();
/// assert_eq!(grid[0][0], Cell::Vowel { vowel: Vowel::A });
/// assert_eq!(grid[0][1], Cell::Star { star: Star::of(Nakshatra::Krittika) });
/// assert_eq!(grid[8][2], Cell::Star { star: Star::Abhijit });
/// assert_eq!(grid[4][4], Cell::Tithi { class: TithiClass::Purna });
/// ```
#[must_use]
pub fn chakra() -> [[Cell; SIDE]; SIDE] {
    let mut grid = [[Cell::Tithi {
        class: TithiClass::Purna,
    }; SIDE]; SIDE];
    let mut put = |(row, column): At, cell: Cell| {
        if let Some(slot) = grid.get_mut(row).and_then(|line| line.get_mut(column)) {
            *slot = cell;
        }
    };
    for ring in 0..4 {
        for (k, at) in corners(ring).into_iter().enumerate() {
            if let Some(&vowel) = Vowel::ALL.get(4 * ring + k) {
                put(at, Cell::Vowel { vowel });
            }
        }
        for (n, at) in ring_sides(ring).into_iter().enumerate() {
            if let Some(cell) = member(ring, n) {
                put(at, cell);
            }
        }
    }
    grid
}

/// One of a graha's three lines of sight (v. 13), named as the graha sees
/// them standing in its star and facing the chakra's centre (C429).
///
/// ```
/// use teistro_core::catalogue::Nakshatra;
/// use teistro_gochar::sarvatobhadra::{Cell, Line, Star, sight};
///
/// // Rohini's front runs straight across to Abhijit.
/// let front = sight(Star::of(Nakshatra::Rohini), Line::Front);
/// assert_eq!(front.last(), Some(&Cell::Star { star: Star::Abhijit }));
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[cfg_attr(feature = "schema", schemars(rename = "VedhaLine"))]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Line {
    /// The diagonal on its left, towards the stars after its own.
    Left,
    /// Straight across, to the star facing it.
    Front,
    /// The diagonal on its right, towards the stars before its own.
    Right,
}

impl Line {
    /// The three, in v. 13's order.
    pub const ALL: [Line; 3] = [Line::Left, Line::Front, Line::Right];
}

/// The step a line takes from a star `n` places from Krittika: inwards
/// from its side, turned half right or half left. Facing the centre from
/// the east side is facing west, the right hand to the north.
fn step(n: usize, line: Line) -> (isize, isize) {
    const INWARD: [(isize, isize); 4] = [(1, 0), (0, -1), (-1, 0), (0, 1)];
    let (down, across) = INWARD.get(n / 7).copied().unwrap_or((1, 0));
    let (right_down, right_across) = (across, -down);
    match line {
        Line::Front => (down, across),
        Line::Right => (down + right_down, across + right_across),
        Line::Left => (down - right_down, across - right_across),
    }
}

/// The cells `line` passes from `star` to the chakra's edge, in order,
/// the star itself left out.
fn sight_in(grid: &[[Cell; SIDE]; SIDE], star: Star, line: Line) -> Vec<Cell> {
    let Some(n) = STARS.iter().position(|s| *s == star) else {
        return Vec::new();
    };
    let Some((mut row, mut column)) = ring_sides(0).get(n).copied() else {
        return Vec::new();
    };
    let (down, across) = step(n, line);
    let mut cells = Vec::new();
    while let (Some(r), Some(c)) = (
        row.checked_add_signed(down),
        column.checked_add_signed(across),
    ) {
        let Some(cell) = grid.get(r).and_then(|grid_row| grid_row.get(c)) else {
            break;
        };
        cells.push(*cell);
        (row, column) = (r, c);
    }
    cells
}

/// The cells `line` passes from a graha in `star`, in order outwards to
/// the star at its far end; whether the front strikes them all is
/// [`FrontVedha`]'s.
///
/// ```
/// use teistro_core::catalogue::{Nakshatra, Rashi};
/// use teistro_gochar::sarvatobhadra::{Cell, Line, Star, sight};
///
/// // Krittika's right runs straight to Bharani, the star behind it.
/// assert_eq!(
///     sight(Star::of(Nakshatra::Krittika), Line::Right),
///     vec![Cell::Star { star: Star::of(Nakshatra::Bharani) }],
/// );
/// // Its left runs through Taurus to Vishakha.
/// let left = sight(Star::of(Nakshatra::Krittika), Line::Left);
/// assert_eq!(left[1], Cell::Rashi { rashi: Rashi::Taurus });
/// assert_eq!(left.last(), Some(&Cell::Star { star: Star::of(Nakshatra::Vishakha) }));
/// ```
#[must_use]
pub fn sight(star: Star, line: Line) -> Vec<Cell> {
    sight_in(&chakra(), star, line)
}


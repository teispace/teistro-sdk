    #[test]
    fn a_name_s_letter_is_struck_by_its_pair_its_pillar_and_its_star() {
        // Saturn in Mrigashira, mean: its front reaches Uttarashadha only.
        // Mars in Mrigashira too, fast: its left runs through ka.
        let transits = sky(
            100.0,
            40.0,
            [
                (Graha::Moon, 200.0),
                (Graha::Mars, 55.0),
                (Graha::Jupiter, 160.0),
                (Graha::Saturn, 55.0),
            ],
        );
        let motions = [
            Motion::Fast,
            Motion::Fast,
            Motion::Mean,
            Motion::Fast,
            Motion::Mean,
        ];
        let read = |letter: char, vowel: Vowel| {
            sarvatobhadra(
                &transits,
                &motions,
                &native(Nakshatra::Ashwini, Some(NameSounds { letter, vowel })),
                SarvatobhadraRules::TEXT,
            )
            .unwrap()
        };
        let strikes = |reading: &SarvatobhadraReading, graha: Graha, point: VedhaPoint| {
            reading.grahas[graha as usize]
                .points
                .iter()
                .any(|p| p.point == point)
        };
        // घ is struck with ka (v. 23).
        assert!(strikes(
            &read('घ', Vowel::A),
            Graha::Mars,
            VedhaPoint::Letter
        ));
        assert!(!strikes(
            &read('घ', Vowel::A),
            Graha::Saturn,
            VedhaPoint::Letter
        ));
        // ब with va (v. 22): Mrigashira's left does not pass va.
        assert!(!strikes(
            &read('ब', Vowel::A),
            Graha::Mars,
            VedhaPoint::Letter
        ));
        // A graha standing in Ardra strikes घ by v. 24 alone.
        let mut in_ardra = transits;
        in_ardra[Graha::Saturn as usize] = Transit::at_longitude(70.0);
        let reading = sarvatobhadra(
            &in_ardra,
            &motions,
            &native(
                Nakshatra::Ashwini,
                Some(NameSounds {
                    letter: 'घ',
                    vowel: Vowel::A,
                }),
            ),
            SarvatobhadraRules::TEXT,
        )
        .unwrap();
        let saturn = &reading.grahas[Graha::Saturn as usize];
        assert_eq!(saturn.place.star, Star::of(Nakshatra::Ardra));
        let letter = saturn
            .points
            .iter()
            .find(|p| p.point == VedhaPoint::Letter)
            .unwrap();
        assert_eq!(letter.by, vec![Reach::Stands]);
        // A Latin letter is refused, naming the field.
        let refused = sarvatobhadra(
            &transits,
            &motions,
            &native(
                Nakshatra::Ashwini,
                Some(NameSounds {
                    letter: 'g',
                    vowel: Vowel::A,
                }),
            ),
            SarvatobhadraRules::TEXT,
        )
        .unwrap_err();
        assert_eq!(refused.field(), Some("native.name.letter"));
    }


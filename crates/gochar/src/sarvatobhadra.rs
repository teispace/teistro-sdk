//! The Sarvatobhadra chakra and its vedha: gochar's second layer
//! (`03-design/gochar.md` §8, cruxes C428 to C432).
//!
//! *Narapati Jayacharya Svarodaya*'s sarvatobhadra (1946 Khemraj print
//! with the Jayalakshmi tika, pp. 55–62, read on the page images): ten
//! lines each way make 81 cells (v. 2); the sixteen vowels go to the
//! corners from the north-east, round and round inwards (v. 3); the 28
//! stars from Krittika to the outer ring, seven a side from the east (v.
//! 4); the twenty letters a va ka ha da, ma ta pa ra ta, na ya bha ja kha,
//! ga sa da cha la to the next ring (v. 5); the twelve signs from Taurus
//! to the next (v. 6); the five tithi groups and the seven weekdays to the
//! last five (vv. 7–9). A graha strikes from its star along three lines,
//! left, front and right (v. 13); the five from Mars look by their motion,
//! right when retrograde, left when fast, ahead when mean (v. 15); the Sun,
//! the Moon and the nodes always along all three (v. 19). Phaladeepika ch.
//! 26 v. 48 reads the chakra's vedhas into gochar: a benefic's brings good,
//! a malefic's sorrow.
//!
//! The grid is **generated by that rule**, not transcribed, and a test
//! holds it to the printed chakra cell for cell.
//!
//! ```
//! use teistro_core::catalogue::{Graha, Nakshatra, Rashi, Tithi, Vara};
//! use teistro_gochar::Transit;
//! use teistro_gochar::sarvatobhadra::{
//!     Motion, NativePoints, SarvatobhadraRules, VedhaPoint, sarvatobhadra,
//! };
//!
//! // Every graha in Rohini (Taurus 15°) but Ketu, opposite Rahu; Saturn
//! // mean in motion, so it looks straight ahead.
//! let mut sky = [Transit::new(Rashi::Taurus, 15.0); 9];
//! sky[Graha::Ketu as usize] = Transit::new(Rashi::Scorpio, 15.0);
//! let motions = [Motion::Fast, Motion::Fast, Motion::Fast, Motion::Fast, Motion::Mean];
//! let native = NativePoints {
//!     nakshatra: Nakshatra::Swati,
//!     rashi: Rashi::Libra,
//!     tithi: Tithi::ShuklaPratipada,
//!     vara: Vara::Ravivara,
//!     name: None,
//! };
//! let reading = sarvatobhadra(&sky, &motions, &native, SarvatobhadraRules::TEXT).unwrap();
//! // Saturn, ahead only: Rohini's front strikes Abhijit and no more.
//! let saturn = &reading.grahas[Graha::Saturn as usize];
//! assert!(saturn.points.is_empty());
//! // The Sun looks along all three lines (v. 19); its left diagonal runs
//! // through va, Gemini, au, Virgo and ra to Swati, the native's star.
//! let star = reading.points.iter().find(|p| p.point == VedhaPoint::Nakshatra).unwrap();
//! assert!(star.malefics.contains(&Graha::Sun));
//! ```


/// What strikes a name's first letter: the letters' cells and the stars a
/// graha strikes it from by standing there.
struct LetterReach {
    cells: Vec<char>,
    stars: Vec<Nakshatra>,
}

/// How the chakra reads a name's first letter (vv. 5, 22–24; C431): one
/// of its twenty as itself, a vowel at a, and the rest by the letter v. 22
/// pairs them with or the pillar v. 23 sets them after, with the star v. 24
/// strikes them from. A nukta's letter is read as its base.
fn letter_reach(letter: char) -> Option<LetterReach> {
    let base = match letter {
        '\u{0958}' => 'क',
        '\u{0959}' => 'ख',
        '\u{095A}' => 'ग',
        '\u{095B}' => 'ज',
        '\u{095C}' => 'ड',
        '\u{095D}' => 'ढ',
        '\u{095E}' => 'फ',
        '\u{095F}' => 'य',
        other => other,
    };
    let reach = |cells: Vec<char>, stars: Vec<Nakshatra>| Some(LetterReach { cells, stars });
    match base {
        'अ' | 'आ' | 'इ' | 'ई' | 'उ' | 'ऊ' | 'ऋ' | 'ॠ' | 'ऌ' | 'ॡ' | 'ए' | 'ऐ' | 'ओ' | 'औ' => {
            reach(vec!['अ'], Vec::new())
        }
        'ब' => reach(vec!['व'], Vec::new()),
        'श' => reach(vec!['स'], Vec::new()),
        'ष' => reach(vec!['ख', 'प'], vec![Nakshatra::Hasta]),
        'घ' | 'छ' => reach(vec!['क'], vec![Nakshatra::Ardra]),
        'ङ' | 'ञ' => reach(
            vec!['क', 'द'],
            vec![Nakshatra::Ardra, Nakshatra::UttaraBhadrapada],
        ),
        'ण' | 'ठ' => reach(vec!['प'], vec![Nakshatra::Hasta]),
        'ध' | 'फ' | 'ढ' => reach(vec!['भ'], vec![Nakshatra::PurvaAshadha]),
        'थ' | 'झ' => reach(vec!['द'], vec![Nakshatra::UttaraBhadrapada]),
        other if LETTERS.contains(&other) => reach(vec![other], Vec::new()),
        _ => None,
    }
}


    #[test]
    fn a_vowel_is_struck_with_its_pair_and_a_corner_from_its_juncture() {
        // Mars in Krittika's first pada (26°40′ to 30°), Fast: its left
        // runs through the letter a; at the north-east juncture it strikes
        // a, u, ḷ, o and Purna (v. 26).
        let transits = sky(
            100.0,
            40.0,
            [
                (Graha::Moon, 200.0),
                (Graha::Mars, 28.0),
                (Graha::Jupiter, 160.0),
                (Graha::Saturn, 250.0),
            ],
        );
        let name = Some(NameSounds {
            letter: 'आ',
            vowel: Vowel::Aa,
        });
        let mut who = native(Nakshatra::Ashwini, name);
        who.tithi = Tithi::Purnima;
        let reading = sarvatobhadra(
            &transits,
            &[Motion::Fast; 5],
            &who,
            SarvatobhadraRules::TEXT,
        )
        .unwrap();
        let mars = &reading.grahas[Graha::Mars as usize];
        assert_eq!(
            (mars.place.nakshatra, mars.place.pada),
            (Nakshatra::Krittika, 1)
        );
        let corner: Vec<Cell> = mars
            .cells
            .iter()
            .filter(|reach| matches!(reach, Reach::Corner { .. }))
            .filter_map(|reach| reach.cell())
            .collect();
        assert_eq!(
            corner,
            vec![
                v(Vowel::A),
                v(Vowel::U),
                v(Vowel::Li),
                v(Vowel::O),
                t(TithiClass::Purna)
            ]
        );
        let struck = |point| mars.points.iter().any(|p| p.point == point);
        // ā is struck with a (v. 21); a name beginning with a vowel is read
        // at the letter a, which Krittika's left passes.
        assert!(struck(VedhaPoint::Vowel));
        assert!(struck(VedhaPoint::Letter));
        assert!(struck(VedhaPoint::Tithi));
        // In Krittika's second pada no corner is struck.
        let mut later = transits;
        later[Graha::Mars as usize] = Transit::at_longitude(31.0);
        let reading =
            sarvatobhadra(&later, &[Motion::Fast; 5], &who, SarvatobhadraRules::TEXT).unwrap();
        assert!(
            reading.grahas[Graha::Mars as usize]
                .cells
                .iter()
                .all(|reach| !matches!(reach, Reach::Corner { .. }))
        );
    }

    #[test]
    fn the_points_list_each_striker_by_its_nature() {
        // The Sun in Rohini looks along all three lines, and its left
        // reaches Swati, the native's star; Jupiter beside it in Rohini,
        // mean, looks ahead only, to Abhijit.
        let transits = sky(
            45.0,
            130.0,
            [
                (Graha::Moon, 140.0),
                (Graha::Mars, 200.0),
                (Graha::Jupiter, 47.0),
                (Graha::Saturn, 250.0),
            ],
        );
        let mut who = native(Nakshatra::Swati, None);
        who.rashi = Rashi::Libra;
        let reading = sarvatobhadra(
            &transits,
            &[Motion::Mean; 5],
            &who,
            SarvatobhadraRules::TEXT,
        )
        .unwrap();
        let star = reading
            .points
            .iter()
            .find(|p| p.point == VedhaPoint::Nakshatra)
            .unwrap();
        assert!(star.malefics.contains(&Graha::Sun));
        let sun = &reading.grahas[Graha::Sun as usize];
        let by = &sun
            .points
            .iter()
            .find(|p| p.point == VedhaPoint::Nakshatra)
            .unwrap()
            .by;
        assert!(matches!(
            by.as_slice(),
            [Reach::Line {
                line: Line::Left,
                ..
            }]
        ));
        assert!(!star.benefics.contains(&Graha::Jupiter));
        assert!(!star.malefics.contains(&Graha::Jupiter));
        // Jupiter shares Taurus with the Sun, so v. 30 makes it malefic.
        assert_eq!(
            reading.grahas[Graha::Jupiter as usize].joined_by,
            vec![Graha::Sun]
        );
        assert_eq!(
            reading.points.iter().map(|p| p.point).collect::<Vec<_>>(),
            vec![
                VedhaPoint::Nakshatra,
                VedhaPoint::Tithi,
                VedhaPoint::Rashi,
                VedhaPoint::Vara
            ]
        );
        // The count is of v. 28's five a malefic strikes, the weekday apart.
        let counted = reading
            .points
            .iter()
            .filter(|p| p.point != VedhaPoint::Vara && !p.malefics.is_empty())
            .count();
        assert_eq!(usize::from(reading.malefic_points), counted);
    }

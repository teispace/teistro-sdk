/// The chapters the pack ships.
const CHAPTERS: [&str; 4] = ["24", "30", "33", "80"];

/// Every rule the chapters ship.
fn chapters() -> Vec<Rule> {
    shipped::nabhasas()
        .iter()
        .filter(|rule| {
            rule.source.text == "BPHS"
                && rule
                    .source
                    .chapter
                    .as_deref()
                    .is_some_and(|chapter| CHAPTERS.contains(&chapter))
        })
        .cloned()
        .collect()
}


/// The chapters the pack ships.
const CHAPTERS: [&str; 5] = ["5", "7", "22", "24", "25"];

/// Every rule the chapters ship.
fn chapters() -> Vec<Rule> {
    shipped::nabhasas()
        .iter()
        .filter(|rule| {
            rule.source.text == "Brihat Jataka"
                && rule
                    .source
                    .chapter
                    .as_deref()
                    .is_some_and(|chapter| CHAPTERS.contains(&chapter))
        })
        .cloned()
        .collect()
}


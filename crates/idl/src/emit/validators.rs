//! The shared validator corpus (`03-design/validator-corpus.md`): for each
//! quantity the description brands, the values every binding's constructor
//! and the Rust newtype must accept, and the values they must refuse.
//!
//! The values sit where an off-by-one lives: on each bound, the double just
//! inside it and the double just outside it. They are written as strings,
//! since JSON holds neither NaN nor an infinity, and every language's
//! standard parser reads `"NaN"`, `"Infinity"`, `"-Infinity"` and a
//! shortest decimal to the same double.

use serde_json::json;

use super::ts::{brand_range, brands};
use crate::model::Api;

/// The corpus's schema.
///
/// ```
/// # use teistro_idl::Api;
/// #
/// # let root = std::path::Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../.."));
/// # let api: Api = serde_json::from_str(&std::fs::read_to_string(root.join("idl/api.json"))?)?;
///
/// use teistro_idl::emit::validators::{self, SCHEMA};
///
/// let corpus: serde_json::Value = serde_json::from_str(&validators::corpus(&api)?)?;
/// assert_eq!(corpus["schema"], SCHEMA);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub const SCHEMA: &str = "teistro-validators/1";

/// The double after `x` towards positive infinity, for a finite `x`: the
/// workspace's toolchain floor predates `f64::next_up`.
fn up(x: f64) -> f64 {
    if x == 0.0 {
        f64::from_bits(1)
    } else if x > 0.0 {
        f64::from_bits(x.to_bits() + 1)
    } else {
        f64::from_bits(x.to_bits() - 1)
    }
}

/// The double before `x`, for a finite `x`.
fn down(x: f64) -> f64 {
    -up(-x)
}

/// A double as the corpus writes it: what each language's parser reads
/// back to the same bits.
fn written(x: f64) -> String {
    if x.is_nan() {
        String::from("NaN")
    } else if x.is_infinite() {
        String::from(if x > 0.0 { "Infinity" } else { "-Infinity" })
    } else if x.abs() >= 1e16 {
        format!("{x:e}")
    } else {
        format!("{x}")
    }
}

/// Renders `idl/validators.json`.
///
/// ```
/// # use teistro_idl::Api;
/// #
/// # let root = std::path::Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../.."));
/// # let api: Api = serde_json::from_str(&std::fs::read_to_string(root.join("idl/api.json"))?)?;
///
/// use teistro_idl::emit::validators;
///
/// // What every binding's constructor is held to, as `cargo xtask gen ffi` writes it.
/// assert_eq!(validators::corpus(&api)?, std::fs::read_to_string(root.join("idl/validators.json"))?);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
///
/// # Errors
///
/// When a brand's range is not two numbers, naming the brand: its bounds
/// are what the corpus is built from, so it cannot be left out quietly.
pub fn corpus(api: &Api) -> Result<String, String> {
    let refused_anywhere = [f64::NAN, f64::INFINITY, f64::NEG_INFINITY, 1e308, -1e308];
    let mut brands_json = Vec::new();
    for (brand, field) in brands(api) {
        let (mut valid, mut invalid) = (Vec::new(), Vec::new());
        if let Some((low, high)) = brand_range(field) {
            let number = |end: &str| -> Result<f64, String> {
                end.parse()
                    .map_err(|_| format!("{brand}: the range end `{end}` is not a number"))
            };
            let (low, high) = (number(low)?, number(high)?);
            valid.extend([low, up(low), low.midpoint(high), down(high), high]);
            invalid.extend([down(low), up(high)]);
        } else {
            valid.push(0.0);
        }
        invalid.extend(refused_anywhere);
        brands_json.push(json!({
            "brand": brand,
            "unit": field.meta.unit,
            "range": field.meta.range,
            "valid": valid.into_iter().map(written).collect::<Vec<_>>(),
            "invalid": invalid.into_iter().map(written).collect::<Vec<_>>(),
        }));
    }
    let corpus = json!({
        "schema": SCHEMA,
        "about": "Generated by `cargo xtask gen ffi` from the description's branded fields; \
                  do not edit. Every binding's constructor and the Rust newtype accept each \
                  `valid` value and refuse each `invalid` one (docs/03-design/validator-corpus.md).",
        "brands": brands_json,
    });
    serde_json::to_string_pretty(&corpus)
        .map(|text| text + "\n")
        .map_err(|error| error.to_string())
}

#[cfg(test)]
#[cfg_attr(coverage_nightly, coverage(off))]
mod tests {
    #![allow(clippy::float_cmp, reason = "the neighbours are exact doubles")]
    #![allow(clippy::unwrap_used, reason = "tests fail by panicking")]

    use super::*;

    #[test]
    fn a_neighbour_is_one_double_away_on_either_side_of_nought() {
        assert_eq!(up(90.0), 90.000_000_000_000_01);
        assert_eq!(down(90.0), 89.999_999_999_999_99);
        assert_eq!(up(-90.0), -89.999_999_999_999_99);
        assert_eq!(down(-90.0), -90.000_000_000_000_01);
        assert_eq!(up(0.0), f64::from_bits(1));
        assert_eq!(down(0.0), -f64::from_bits(1));
        for x in [-500.0, -180.0, 0.25, 12_000.0] {
            assert_eq!(down(up(x)), x);
            assert!(up(x) > x && down(x) < x);
        }
    }

    #[test]
    fn every_value_reads_back_as_the_double_it_was() {
        for x in [90.0, up(90.0), down(-180.0), 1e308, -1e308, 5750.0, 0.0] {
            assert_eq!(written(x).parse::<f64>().unwrap(), x, "{}", written(x));
        }
        assert_eq!(written(f64::NAN), "NaN");
        assert_eq!(written(f64::NEG_INFINITY), "-Infinity");
        assert_eq!(written(f64::INFINITY), "Infinity");
        assert!("Infinity".parse::<f64>().unwrap().is_infinite());
    }

    fn api() -> Api {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../idl/api.json");
        serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap()
    }

    fn brand<'c>(corpus: &'c serde_json::Value, name: &str) -> &'c serde_json::Value {
        corpus["brands"]
            .as_array()
            .unwrap()
            .iter()
            .find(|b| b["brand"] == name)
            .unwrap()
    }

    #[test]
    fn a_brand_is_held_to_its_range_or_to_nought_and_the_refusals() {
        let mut api = api();
        let checked = corpus(&api).unwrap();
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../idl/validators.json");
        assert_eq!(checked, std::fs::read_to_string(path).unwrap());
        let before: serde_json::Value = serde_json::from_str(&checked).unwrap();
        assert_eq!(
            brand(&before, "latitude").pointer("/valid/0"),
            Some(&json!("-90")),
            "a range's low end is valid"
        );
        for field in api.structs.iter_mut().flat_map(|s| &mut s.fields) {
            if field.meta.brand.as_deref() == Some("latitude") {
                field.meta.range = None;
            }
        }
        let after: serde_json::Value = serde_json::from_str(&corpus(&api).unwrap()).unwrap();
        let latitude = brand(&after, "latitude");
        assert_eq!(latitude["valid"], json!(["0"]), "no range: nought alone");
        assert_eq!(
            latitude["invalid"],
            json!(["NaN", "Infinity", "-Infinity", "1e308", "-1e308"])
        );
        for field in api.structs.iter_mut().flat_map(|s| &mut s.fields) {
            if field.meta.brand.as_deref() == Some("latitude") {
                field.meta.range = Some(String::from("[south,90]"));
            }
        }
        assert_eq!(
            corpus(&api).unwrap_err(),
            "latitude: the range end `south` is not a number"
        );
    }
}

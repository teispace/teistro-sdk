fn render_decoder(out: &mut String, schema: &BlobSchema) {
    let name = blob_type(schema);
    let _ = writeln!(
        out,
        "/**\n * Decodes a {name} blob: {}\n *\n * @param {{Uint8Array}} bytes the blob the library returned\n */\nexport function decode{name}(bytes) {{\n  const blob = open(bytes, {}, '{}');\n  const out = {{}};",
        schema.doc, schema.id, schema.name
    );
    for s in &schema.sections {
        let _ = writeln!(
            out,
            "  {{\n    const at = section(blob, {}, '{}');",
            s.id, s.name
        );
        match s.kind {
            SectionKind::Fixed => {
                let mut slot = 0usize;
                for f in &s.fields {
                    if f.name != "reserved" {
                        let _ = writeln!(
                            out,
                            "    out.{} = READERS.{}(blob.dv, at.offset + {slot});",
                            camel(&f.name),
                            f.scalar.rust_name()
                        );
                    }
                    slot += crate::blob::SLOT;
                }
            }
            SectionKind::Columns => {
                let _ = writeln!(out, "    out.{} = {{", camel(&s.name));
                for (i, f) in s.fields.iter().enumerate() {
                    let _ = writeln!(
                        out,
                        "      {}: column(blob, at, {i}, '{}', at.count),",
                        camel(&f.name),
                        f.scalar.rust_name()
                    );
                }
                let _ = writeln!(out, "      length: at.count,\n    }};");
            }
            SectionKind::Bytes => {
                let _ = writeln!(out, "    out.{} = text(blob, at);", camel(&s.name));
            }
        }
        let _ = writeln!(out, "  }}");
    }
    let _ = writeln!(out, "  return out;\n}}\n");
}


    use super::*;
    use crate::model::{EnumValue, Meta};

    fn toy() -> Api {
        let mut api: Api = serde_json::from_str(
            r#"{"schema":"x","abi_version":3,"sdk_version":"1.2.3","prefix":"ts_","sources":[],
                "constants":[],"enums":[],"opaques":[],"callbacks":[],"structs":[],"functions":[],
                "blobs":[],"records":[]}"#,
        )
        .unwrap();
        api.enums.push(EnumDef {
            name: String::from("Graha"),
            doc: String::from("The grahas <and> more."),
            repr: Scalar::U16,
            kind: Some(String::from("graha")),
            values: vec![EnumValue {
                name: String::from("Sun"),
                value: 0,
                doc: String::from("The Sun"),
                key: String::from("SUN"),
                deprecated: false,
            }],
            source: String::new(),
        });
        api.structs.push(StructDef {
            name: String::from("TsPair"),
            doc: String::from("A pair."),
            role: StructRole::Object,
            fields: vec![
                FieldDef {
                    name: String::from("flag"),
                    ty: TypeRef::scalar(Scalar::U8),
                    doc: String::from("A flag."),
                    meta: Meta::default(),
                },
                FieldDef {
                    name: String::from("native"),
                    ty: TypeRef::scalar(Scalar::F64),
                    doc: String::from("A value."),
                    meta: Meta::default(),
                },
            ],
            source: String::new(),
        });
        api
    }

    #[test]
    fn a_shown_struct_is_a_record_that_checks_what_c_cannot_hold() {
        let files = render(&toy());
        let pair = files
            .iter()
            .find(|f| f.path == "com/teispace/teistro/Pair.java")
            .unwrap();
        // A keyword is renamed, an unsigned byte is carried as an int and
        // checked by the name the caller wrote, and nothing is cast twice.
        assert!(
            pair.text
                .contains("public record Pair(\n        int flag,\n        double nativeValue) {")
        );
        assert!(pair.text.contains("Values.u8(\"flag\", flag)"));
        assert!(pair.text.contains("NATIVE.set(raw, 0L, nativeValue);"));
        assert!(
            pair.text
                .contains("Byte.toUnsignedInt((byte) Native.TsPair.FLAG.get(raw, 0L))")
        );
        assert!(
            files
                .iter()
                .any(|f| f.path == "com/teispace/teistro/Values.java")
        );
    }

    #[test]
    fn a_catalogued_enum_has_its_unknown_and_its_full_key() {
        let files = render(&toy());
        let graha = files
            .iter()
            .find(|f| f.path == "com/teispace/teistro/Graha.java")
            .unwrap();
        assert!(
            graha
                .text
                .contains("public enum Graha implements Catalogued {")
        );
        assert!(graha.text.contains("    SUN(0, \"SUN\")"));
        assert!(graha.text.contains("    UNKNOWN(-1, \"UNKNOWN\");"));
        assert!(graha.text.contains("return \"graha.\" + key;"));
        assert!(graha.text.contains("The grahas &lt;and&gt; more."));
    }

    #[test]
    fn a_layout_writes_its_padding_and_a_keyword_field_is_renamed() {
        let native = render(&toy()).pop().unwrap();
        assert_eq!(native.path, "com/teispace/teistro/ffi/Native.java");
        assert!(native.text.contains(
            "JAVA_BYTE.withName(\"flag\"),\n            MemoryLayout.paddingLayout(7),\n            JAVA_DOUBLE.withName(\"native\")"
        ));
        assert!(native.text.contains("public static final long SIZE = 16;"));
        assert!(
            native
                .text
                .contains("public static final long NATIVE_OFFSET = 8;")
        );
        assert_eq!(identifier("native"), "nativeValue");
        assert_eq!(identifier("lon_deg"), "lonDeg");
        assert_eq!(constant("2ND"), "_2ND");
    }

    #[test]
    fn javadoc_is_html_and_a_leading_at_is_not_a_tag() {
        assert_eq!(
            javadoc("a < b & c\n@unit deg", ""),
            "/**\n * a &lt; b &amp; c\n * &#64;unit deg\n */\n"
        );
        assert_eq!(literal("a\"b\\c\n"), "\"a\\\"b\\\\c\\n\"");
    }

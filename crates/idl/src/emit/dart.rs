/// The typed list a column of a scalar decodes into.
fn typed_list(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::U8 | Scalar::Bool => "Uint8List",
        Scalar::U16 => "Uint16List",
        Scalar::U32 => "Uint32List",
        Scalar::U64 => "Uint64List",
        Scalar::I8 => "Int8List",
        Scalar::I16 => "Int16List",
        Scalar::I32 => "Int32List",
        Scalar::I64 => "Int64List",
        Scalar::F32 => "Float32List",
        Scalar::F64 | Scalar::Usize | Scalar::Isize => "Float64List",
    }
}

fn byte_data_getter(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::F64 => "getFloat64",
        Scalar::F32 => "getFloat32",
        Scalar::I8 => "getInt8",
        Scalar::I16 => "getInt16",
        Scalar::I32 => "getInt32",
        Scalar::I64 => "getInt64",
        Scalar::U8 | Scalar::Bool => "getUint8",
        Scalar::U16 => "getUint16",
        _ => "getUint32",
    }
}

/// Renders `blob.dart`: one decoder per result blob over the `TSRB`
/// layout, the columns as views over the bytes rather than copies.
#[must_use]
pub fn decoders(api: &Api) -> String {
    let mut out = preamble(
        api,
        "\n\nimport 'dart:convert';\nimport 'dart:typed_data';\n",
    );
    out.push_str(DECODER_PRELUDE);
    for schema in &api.blobs {
        render_decoder(&mut out, schema);
    }
    out
}

const DECODER_PRELUDE: &str = r"
const int _magic = 0x42525354; // 'TSRB'
const int _version = 1;
const int _headerLength = 32;
const int _entryLength = 16;

/// One section of a blob, as its table of contents describes it.
final class _Section {
  const _Section(this.offset, this.length, this.count);

  final int offset;
  final int length;
  final int count;
}

/// A blob opened for reading: the bytes, a view over them, and the table.
final class _Blob {
  _Blob(this.bytes, this.data, this.sections);

  final Uint8List bytes;
  final ByteData data;
  final Map<int, _Section> sections;

  /// Reads the header and the table, checking every offset.
  factory _Blob.open(Uint8List raw, int schemaId, String schemaName) {
    // A column is read as a typed list over these bytes, and a typed list
    // must start on a multiple of its element's size. A view handed to us
    // at an offset that cannot give that is copied once, here, rather
    // than misread or refused.
    final input = raw.offsetInBytes % 8 == 0
        ? raw
        : Uint8List.fromList(raw);
    final data = ByteData.sublistView(input);
    if (input.lengthInBytes < _headerLength ||
        data.getUint32(0, Endian.little) != _magic) {
      throw const FormatException('not a Teistro result blob');
    }
    final version = data.getUint32(4, Endian.little);
    if (version != _version) {
      throw FormatException(
        'blob layout version $version, this decoder reads version $_version',
      );
    }
    final total = data.getUint32(12, Endian.little);
    if (total != input.lengthInBytes) {
      throw FormatException(
        'the header says $total bytes, ${input.lengthInBytes} were given',
      );
    }
    final id = data.getUint32(16, Endian.little);
    if (id != schemaId) {
      throw FormatException('blob schema $id, expected $schemaId ($schemaName)');
    }
    final count = data.getUint32(8, Endian.little);
    final sections = <int, _Section>{};
    for (var i = 0; i < count; i++) {
      final at = _headerLength + i * _entryLength;
      final section = _Section(
        data.getUint32(at + 4, Endian.little),
        data.getUint32(at + 8, Endian.little),
        data.getUint32(at + 12, Endian.little),
      );
      if (section.offset + section.length > total) {
        throw FormatException(
          'section ${data.getUint32(at, Endian.little)} runs past the end of the blob',
        );
      }
      sections[data.getUint32(at, Endian.little)] = section;
    }
    return _Blob(input, data, sections);
  }

  /// The section with an id, or a [FormatException] naming what is missing.
  _Section section(int id, String name) {
    final found = sections[id];
    if (found == null) {
      throw FormatException('the blob carries no `$name` section');
    }
    return found;
  }

  /// The offset of one column of a column section.
  int columnOffset(_Section at, int index) =>
      at.offset + data.getUint32(at.offset + index * 4, Endian.little);

  /// A bytes section as the UTF-8 text the library wrote.
  String text(_Section at) =>
      utf8.decode(Uint8List.sublistView(bytes, at.offset, at.offset + at.count));
}
";

fn render_decoder(out: &mut String, schema: &BlobSchema) {
    let name = pascal(&schema.name);
    for section in schema
        .sections
        .iter()
        .filter(|s| s.kind == SectionKind::Columns)
    {
        render_column_class(out, &name, section);
    }
    render_decoded_class(out, &name, schema);
    render_decode_function(out, &name, schema);
}

/// A column section as its own class: one typed list per column.
fn render_column_class(out: &mut String, name: &str, section: &SectionSchema) {
    let class = format!("{name}{}", pascal(&section.name));
    let _ = writeln!(
        out,
        "/// The `{}` section of a {name} blob: one typed list per column, each a\n/// view over the blob's bytes rather than a copy.\n///\n/// {}\nfinal class {class} {{\n  const {class}({{",
        section.name, section.doc
    );
    for column in &section.fields {
        let _ = writeln!(out, "    required this.{},", identifier(&column.name));
    }
    let _ = writeln!(out, "    required this.length,\n  }});\n");
    for column in &section.fields {
        let _ = writeln!(
            out,
            "{}  final {} {};\n",
            doc(&column.doc, "  "),
            typed_list(column.scalar),
            identifier(&column.name)
        );
    }
    let _ = writeln!(
        out,
        "  /// The number of rows every column holds.\n  final int length;\n}}\n"
    );
}

/// The decoded blob: a field per fixed value, per column section and per
/// bytes section.
fn render_decoded_class(out: &mut String, name: &str, schema: &BlobSchema) {
    let _ = writeln!(
        out,
        "/// A decoded {name} blob.\n///\n/// {}\nfinal class {name} {{\n  const {name}({{",
        schema.doc
    );
    for section in &schema.sections {
        match section.kind {
            SectionKind::Fixed => {
                for field in section.fields.iter().filter(|f| f.name != "reserved") {
                    let _ = writeln!(out, "    required this.{},", identifier(&field.name));
                }
            }
            SectionKind::Columns | SectionKind::Bytes => {
                let _ = writeln!(out, "    required this.{},", identifier(&section.name));
            }
        }
    }
    let _ = writeln!(out, "  }});\n");
    for section in &schema.sections {
        match section.kind {
            SectionKind::Fixed => {
                for field in section.fields.iter().filter(|f| f.name != "reserved") {
                    let _ = writeln!(
                        out,
                        "{}  final int {};\n",
                        doc(&field.doc, "  "),
                        identifier(&field.name)
                    );
                }
            }
            SectionKind::Columns => {
                let _ = writeln!(
                    out,
                    "{}  final {name}{} {};\n",
                    doc(&section.doc, "  "),
                    pascal(&section.name),
                    identifier(&section.name)
                );
            }
            SectionKind::Bytes => {
                let _ = writeln!(
                    out,
                    "{}  final String {};\n",
                    doc(&section.doc, "  "),
                    identifier(&section.name)
                );
            }
        }
    }
    let _ = writeln!(out, "}}\n");
}

/// The function that reads a blob into that class.
fn render_decode_function(out: &mut String, name: &str, schema: &BlobSchema) {
    let _ = writeln!(
        out,
        "/// Decodes a {name} blob. The columns are views over `bytes`, so the\n/// buffer must outlive the result; a blob of another layout version or\n/// another schema is a [FormatException].\n{name} decode{name}(Uint8List bytes) {{\n  final blob = _Blob.open(bytes, {}, '{}');",
        schema.id, schema.name
    );
    let mut arguments = Vec::new();
    for section in &schema.sections {
        let at = format!("at{}", pascal(&section.name));
        let _ = writeln!(
            out,
            "  final {at} = blob.section({}, '{}');",
            section.id, section.name
        );
        match section.kind {
            SectionKind::Fixed => {
                let mut slot = 0usize;
                for field in &section.fields {
                    if field.name != "reserved" {
                        // A one-byte read takes no endianness, and Dart's
                        // `ByteData` refuses the argument.
                        let endian = if field.scalar.width(8) == 1 {
                            ""
                        } else {
                            ", Endian.little"
                        };
                        arguments.push(format!(
                            "    {}: blob.data.{}({at}.offset + {slot}{endian}),",
                            identifier(&field.name),
                            byte_data_getter(field.scalar)
                        ));
                    }
                    slot += crate::blob::SLOT;
                }
            }
            SectionKind::Columns => {
                let mut columns = Vec::new();
                for (index, column) in section.fields.iter().enumerate() {
                    columns.push(format!(
                        "      {}: {}.sublistView(\n        blob.bytes,\n        blob.columnOffset({at}, {index}),\n        blob.columnOffset({at}, {index}) + {at}.count * {},\n      ),",
                        identifier(&column.name),
                        typed_list(column.scalar),
                        column.scalar.width(8)
                    ));
                }
                arguments.push(format!(
                    "    {}: {name}{}(\n{}\n      length: {at}.count,\n    ),",
                    identifier(&section.name),
                    pascal(&section.name),
                    columns.join("\n")
                ));
            }
            SectionKind::Bytes => {
                arguments.push(format!(
                    "    {}: blob.text({at}),",
                    identifier(&section.name)
                ));
            }
        }
    }
    let _ = writeln!(
        out,
        "  return {name}(\n{}\n  );\n}}\n",
        arguments.join("\n")
    );
}

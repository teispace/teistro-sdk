//! The TypeScript surface of the Node binding and the blob decoder, both
//! from the description: every field carries its documentation, unit,
//! range and example so completion shows them (ADR-0023).

use std::fmt::Write;

use crate::common::{
    DocStyle, binding_name, block_comment, callback_shape, constructor, field_doc,
    is_free_function, is_object, is_visible, kebab, message_function, method_name, methods,
    pointee_struct, provider_callback, provider_type_name, returned_scalar,
};
use crate::model::{Api, FunctionDef, Role, TypeRef, camel, strip_prefix};

fn ts_scalar(ty: &TypeRef) -> &'static str {
    match ty {
        TypeRef::Scalar { name } if name == "bool" => "boolean",
        TypeRef::Scalar { name } if name == "i64" || name == "u64" => "bigint",
        _ => "number",
    }
}

/// Renders `generated.d.ts`.
pub(crate) fn render_types(api: &Api) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "/* GENERATED by teistro-spike-a-gen from {}. Do not edit; run the generator. */\n",
        api.source
    );
    for e in &api.enums {
        let name = binding_name(api, &e.name);
        let union: Vec<String> = e
            .values
            .iter()
            .map(|v| format!("'{}'", kebab(&v.name)))
            .collect();
        let _ = writeln!(
            out,
            "{}export type {name} = {};",
            block_comment(&e.doc, ""),
            union.join(" | ")
        );
        let _ = writeln!(out, "export declare const {name}: {{");
        for v in &e.values {
            let _ = writeln!(
                out,
                "{}  readonly {}: '{}';",
                block_comment(&v.doc, "  "),
                v.name,
                kebab(&v.name)
            );
        }
        let _ = writeln!(out, "}};\n");
    }
    for s in api.structs.iter().filter(|s| is_object(s)) {
        let _ = writeln!(
            out,
            "{}export interface {} {{",
            block_comment(&s.doc, ""),
            binding_name(api, &s.name)
        );
        for f in s.fields.iter().filter(|f| is_visible(f)) {
            let ty = f
                .meta
                .enum_name
                .as_ref()
                .map_or_else(|| ts_scalar(&f.ty).to_string(), |e| binding_name(api, e));
            let _ = writeln!(
                out,
                "{}  {}: {ty};",
                block_comment(&field_doc(f, DocStyle::JsDoc), "  "),
                camel(&f.name)
            );
        }
        let _ = writeln!(out, "}}\n");
    }
    if let Some((_, _, c)) = provider_callback(api) {
        if let Some(shape) = callback_shape(c) {
            let args: Vec<String> = shape
                .args
                .iter()
                .map(|p| format!("{}: {}", camel(&p.name), ts_scalar(&p.ty)))
                .collect();
            let _ = writeln!(
                out,
                "{}export type {} = ({}) => {};\n",
                block_comment(&c.doc, ""),
                provider_type_name(api, c),
                args.join(", "),
                binding_name(api, shape.out)
            );
        }
    }
    for o in &api.opaques {
        let name = binding_name(api, &o.name);
        let _ = writeln!(
            out,
            "{}export declare class {name} {{",
            block_comment(&o.doc, "")
        );
        if let Some(ctor) = constructor(api) {
            let _ = writeln!(
                out,
                "{}  constructor({});",
                block_comment(&ctor.doc, "  "),
                constructor_params(api, ctor).join(", ")
            );
        }
        for m in methods(api) {
            let (params, returns) = signature(api, m);
            let _ = writeln!(
                out,
                "{}  {}({}): {returns};",
                block_comment(&m.doc, "  "),
                camel(&method_name(api, &o.name, m)),
                params.join(", ")
            );
        }
        let _ = writeln!(out, "}}\n");
    }
    for f in api.functions.iter().filter(|f| is_free_function(f)) {
        let (params, returns) = signature(api, f);
        let _ = writeln!(
            out,
            "{}export declare function {}({}): {returns};\n",
            block_comment(&f.doc, ""),
            camel(&strip_prefix(&f.name, &api.prefix)),
            params.join(", ")
        );
    }
    out
}

fn constructor_params(api: &Api, ctor: &FunctionDef) -> Vec<String> {
    let mut params = Vec::new();
    for p in &ctor.params {
        match p.role {
            Role::StructIn => {
                if let Some(s) = pointee_struct(p) {
                    params.push(format!("{}: {}", camel(&p.name), binding_name(api, s)));
                }
            }
            Role::VtableIn => {
                if let Some((_, _, c)) = provider_callback(api) {
                    params.push(format!("provider?: {} | null", provider_type_name(api, c)));
                }
            }
            _ => {}
        }
    }
    params
}

fn signature(api: &Api, f: &FunctionDef) -> (Vec<String>, String) {
    let mut params = Vec::new();
    let mut returns = String::from("void");
    for p in &f.params {
        match p.role {
            Role::Value => {
                let ty = match &p.ty {
                    TypeRef::Enum { name } => binding_name(api, name),
                    other => ts_scalar(other).to_string(),
                };
                params.push(format!("{}: {ty}", camel(&p.name)));
            }
            Role::StructOut => {
                if let Some(s) = pointee_struct(p) {
                    returns = binding_name(api, s);
                }
            }
            Role::BlobOut => returns = String::from("Uint8Array"),
            _ => {}
        }
    }
    if message_function(api).is_some_and(|m| m.name == f.name) {
        returns = String::from("string");
    } else if returns == "void" {
        if let Some(scalar) = returned_scalar(f) {
            returns = ts_scalar(&TypeRef::Scalar {
                name: scalar.to_string(),
            })
            .to_string();
        }
    }
    (params, returns)
}

/// Renders `blob.js`: the decoder of the result blob as zero-copy typed
/// array views over the buffer, an eager tree builder and a lazy row view.
pub(crate) fn render_decoder(api: &Api) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "/* GENERATED by teistro-spike-a-gen from {}. Do not edit; run the generator. */\n\nconst MAGIC = {};\nconst VERSION = {};\n\nconst VIEWS = {{\n  u8: Uint8Array,\n  i8: Int8Array,\n  u16: Uint16Array,\n  i16: Int16Array,\n  u32: Uint32Array,\n  i32: Int32Array,\n  i64: BigInt64Array,\n  u64: BigUint64Array,\n  f32: Float32Array,\n  f64: Float64Array,\n}};\n\n/** The bytes as an 8-aligned view, copying only when the caller's buffer is not aligned. */\nfunction aligned(bytes) {{\n  if (bytes.byteOffset % 8 === 0) return bytes;\n  const copy = new Uint8Array(bytes.byteLength);\n  copy.set(bytes);\n  return copy;\n}}\n\nfunction column(bytes, dv, sectionOffset, dirAt, index, type, count) {{\n  const offset = sectionOffset + dv.getUint32(dirAt + index * 4, true);\n  return new VIEWS[type](bytes.buffer, bytes.byteOffset + offset, count);\n}}\n",
        api.source, api.blob.magic, api.blob.version
    );
    let _ = writeln!(
        out,
        "/**\n * Decodes a chart blob into typed-array columns without copying.\n * @param {{Uint8Array}} input the bytes returned by the native call\n */\nexport function decodeChart(input) {{\n  const bytes = aligned(input);\n  const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);\n  if (dv.getUint32(0, true) !== MAGIC) throw new Error('not a TSPB blob');\n  const version = dv.getUint32(4, true);\n  if (version !== VERSION) throw new Error(`blob version ${{version}}, expected ${{VERSION}}`);\n  const sectionCount = dv.getUint32(8, true);\n  const sections = new Map();\n  for (let i = 0; i < sectionCount; i += 1) {{\n    const at = 32 + i * 16;\n    sections.set(dv.getUint32(at, true), {{ offset: dv.getUint32(at + 4, true), length: dv.getUint32(at + 8, true), count: dv.getUint32(at + 12, true) }});\n  }}\n  const result = {{}};"
    );
    for s in &api.blob.sections {
        let _ = writeln!(
            out,
            "  {{\n    const section = sections.get({});\n    if (!section) throw new Error('section {} is missing');",
            s.id, s.name
        );
        if s.kind == "fixed" {
            let mut at = 0usize;
            for f in &s.fields {
                if f.name != "reserved" {
                    let getter = match f.ty.as_str() {
                        "f64" => "getFloat64",
                        "f32" => "getFloat32",
                        "i32" => "getInt32",
                        "i64" => "getBigInt64",
                        "u8" => "getUint8",
                        _ => "getUint32",
                    };
                    let _ = writeln!(
                        out,
                        "    result.{} = dv.{getter}(section.offset + {at}, true);",
                        camel(&f.name)
                    );
                }
                at += f.width();
            }
        } else {
            let _ = writeln!(
                out,
                "    const dirAt = section.offset;\n    result.{} = {{",
                camel(&s.name)
            );
            for (i, f) in s.fields.iter().enumerate() {
                let _ = writeln!(
                    out,
                    "      {}: column(bytes, dv, section.offset, dirAt, {i}, '{}', section.count),",
                    camel(&f.name),
                    f.ty
                );
            }
            let _ = writeln!(out, "      length: section.count,\n    }};");
        }
        let _ = writeln!(out, "  }}");
    }
    let _ = writeln!(out, "  return result;\n}}\n");
    if let Some(dasha) = api
        .blob
        .sections
        .iter()
        .find(|s| s.fields.iter().any(|f| f.name == "parent"))
    {
        let name = camel(&dasha.name);
        let _ = writeln!(
            out,
            "/** Builds the nested tree eagerly: one object per row, children attached through the parent links. */\nexport function {name}Tree(decoded) {{\n  const rows = decoded.{name};\n  const nodes = new Array(rows.length);\n  const roots = [];\n  for (let i = 0; i < rows.length; i += 1) {{\n    const node = {{ lord: rows.lord[i], level: rows.level[i], startJd: rows.startJd[i], endJd: rows.endJd[i], children: [] }};\n    nodes[i] = node;\n    const parent = rows.parent[i];\n    if (parent < 0) roots.push(node); else nodes[parent].children.push(node);\n  }}\n  return roots;\n}}\n\n/** One row as a plain object, built on demand; the columns stay where they are. */\nexport function {name}Row(decoded, i) {{\n  const rows = decoded.{name};\n  return {{ lord: rows.lord[i], level: rows.level[i], parent: rows.parent[i], startJd: rows.startJd[i], endJd: rows.endJd[i] }};\n}}"
        );
    }
    out
}
